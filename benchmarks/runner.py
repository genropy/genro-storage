def percentile(values, quantile):
    values = sorted(values)
    return values[max(0, math.ceil(quantile * len(values)) - 1)]


def digest(data):
    return hashlib.sha256(data).hexdigest()


def require(condition, message):
    # Correctness gates must remain active even with python -O.
    if not condition:
        raise AssertionError(message)


def revision(root):
    result = subprocess.run(
        ["git", "-C", str(root), "rev-parse", "HEAD"], capture_output=True, text=True
    )
    return result.stdout.strip() or None


def source_digest(root, pattern):
    value = hashlib.sha256()
    for path in sorted(Path(root).glob(pattern)):
        value.update(str(path.relative_to(root)).encode())
        value.update(path.read_bytes())
    return value.hexdigest()


class Fixtures:
    def __init__(self, target, run_id):
        self.target = target
        self.prefix = f"genro-storage-bench/{run_id}/"
        self.client = target.client()
        self.payloads = {}
        self.hashes = {}
        self.versioned = False

    def put(self, path, data):
        self.client.put_object(Bucket=self.target.bucket, Key=self.prefix + path, Body=data)

    def read(self, path):
        response = self.client.get_object(Bucket=self.target.bucket, Key=self.prefix + path)
        with response["Body"] as stream:
            return stream.read()

    def prepare(self, sizes, list_count, history):
        status = self.client.get_bucket_versioning(Bucket=self.target.bucket).get("Status")
        self.versioned = status in ("Enabled", "Suspended")
        if history > 1 and status != "Enabled":
            raise ValueError("--history > 1 requires an already version-enabled bucket")
        rng = random.Random(8319)
        for size in sizes:
            data = rng.randbytes(size)
            self.payloads[size] = data
            self.hashes[size] = digest(data)
            for _ in range(history):
                self.put(f"files/{size}.bin", data)
        for index in range(list_count):
            for _ in range(history):
                self.put(f"listing/{index:06d}.bin", b"listing-data")

    def cleanup(self):
        # Only a prefix generated by this process is eligible for deletion.
        parts = self.prefix.split("/")
        if len(parts) != 3 or parts[0] != "genro-storage-bench" or parts[2] != "":
            raise ValueError("Unsafe cleanup prefix")
        uuid.UUID(parts[1])
        paginator = "list_object_versions" if self.versioned else "list_objects_v2"
        objects = []
        for page in self.client.get_paginator(paginator).paginate(
            Bucket=self.target.bucket, Prefix=self.prefix
        ):
            if self.versioned:
                objects.extend(
                    {"Key": item["Key"], "VersionId": item["VersionId"]}
                    for group in ("Versions", "DeleteMarkers")
                    for item in page.get(group, [])
                )
            else:
                objects.extend({"Key": item["Key"]} for item in page.get("Contents", []))
        for offset in range(0, len(objects), 1000):
            response = self.client.delete_objects(
                Bucket=self.target.bucket,
                Delete={"Objects": objects[offset : offset + 1000], "Quiet": True},
            )
            if response.get("Errors"):
                raise RuntimeError("Benchmark object cleanup failed")

    def check(self, op, result, source, dest, size, list_count):
        if op == "exists":
            require(result is True, "Existing fixture was not found")
        elif op == "missing":
            require(result is False, "Missing fixture was reported as present")
        elif op == "attrs":
            require(result[0] is not None and result[1:] == (size, False), "Wrong attributes")
        elif op in ("listing", "tree_attrs"):
            expected = [f"{index:06d}.bin" for index in range(list_count)]
            names = result if op == "listing" else [entry[0] for entry in result]
            require(names == expected, "Incomplete or incorrect listing")
            if op == "tree_attrs":
                require(
                    all(attrs[0] is not None and attrs[1:] == (12, False) for _, attrs in result),
                    "Wrong tree attributes",
                )
        elif op in ("read", "local_path"):
            require(digest(result) == self.hashes[size], "Read content mismatch")
        else:
            require(digest(self.read(dest)) == self.hashes[size], "Written content mismatch")
            if op == "move":
                from botocore.exceptions import ClientError

                try:
                    self.client.head_object(Bucket=self.target.bucket, Key=self.prefix + source)
                except ClientError as exc:
                    if exc.response["Error"]["Code"] not in ("404", "NoSuchKey", "NotFound"):
                        raise
                else:
                    raise AssertionError("Move did not remove the source")


def invoke(adapter, op, source, dest, data):
    if op == "exists":
        return adapter.exists(source)
    if op == "missing":
        return adapter.exists("missing/never-created.bin")
    if op == "attrs":
        return adapter.attrs(source)
    if op == "listing":
        return adapter.listing("listing")
    if op == "tree_attrs":
        return [(name, adapter.attrs("listing/" + name)) for name in adapter.listing("listing")]
    if op == "read":
        return adapter.read(source)
    if op == "write":
        return adapter.write(dest, data)
    if op == "copy":
        return adapter.copy(source, dest)
    if op == "move":
        return adapter.move(source, dest)
    with adapter.local_path(source) as path:
        return Path(path).read_bytes()


def trial(adapter, fixtures, op, size, workers, calls, cache, executor, list_count):
    tasks = []
    for _ in range(calls):
        unique = uuid.uuid4().hex
        source = f"files/{size}.bin"
        dest = f"work/{unique}/dest.bin"
        if op == "move":
            source = f"work/{unique}/source.bin"
            fixtures.put(source, fixtures.payloads[size])
        tasks.append((source, dest))
    if cache == "cold":
        adapter.invalidate()
    adapter.requests.reset()

    def timed(task):
        start = time.perf_counter()
        try:
            result = invoke(adapter, op, *task, fixtures.payloads[size])
            return time.perf_counter() - start, result, None
        except Exception as exc:
            return time.perf_counter() - start, None, type(exc).__name__

    start = time.perf_counter()
    if workers == 1:
        results = [timed(task) for task in tasks]
    else:
        results = list(executor.map(timed, tasks))
    elapsed = time.perf_counter() - start
    requests = adapter.requests.snapshot()
    errors = []
    if adapter.always_http and not requests:
        errors.append("MissingHttpInstrumentation")
    for task, (_, result, error) in zip(tasks, results):
        if error:
            errors.append(error)
            continue
        try:
            fixtures.check(op, result, *task, size, list_count)
        except Exception as exc:
            errors.append(type(exc).__name__)
    # Do not retain read buffers between trials.
    return dict(
        elapsed_s=elapsed,
        latencies_s=[item[0] for item in results],
        requests=requests,
        errors=errors,
        calls=calls,
    )


def summarize(samples):
    groups = defaultdict(list)
    keys = ("adapter", "operation", "size_bytes", "workers", "cache")
    for sample in samples:
        if not sample.get("warmup"):
            groups[tuple(sample[key] for key in keys)].append(sample)
    result = []
    for key, rows in sorted(groups.items()):
        good = [row for row in rows if not row["errors"]]
        entry = dict(zip(keys, key))
        entry.update(samples=len(rows), failed_samples=len(rows) - len(good))
        if good:
            latencies = [value for row in good for value in row["latencies_s"]]
            elapsed = sum(row["elapsed_s"] for row in good)
            calls = sum(row["calls"] for row in good)
            entry.update(
                median_ms=statistics.median(latencies) * 1000,
                p95_ms=percentile(latencies, 0.95) * 1000,
                ops_s=calls / elapsed,
                http_per_op=sum(sum(row["requests"].values()) for row in good) / calls,
            )
            if entry["operation"] in ("read", "write", "copy", "move", "local_path"):
                entry["logical_mib_s"] = calls * entry["size_bytes"] / elapsed / 2**20
        result.append(entry)
    return sorted(
        result,
        key=lambda row: (
            row["operation"],
            row["size_bytes"],
            row["workers"],
            row["cache"],
            row["adapter"],
        ),
    )


def save_report(output, metadata, samples):
    output.mkdir(parents=True, exist_ok=True)
    summary = summarize(samples)
    payload = dict(metadata=metadata, samples=samples, summary=summary)
    temporary = output / "results.json.tmp"
    temporary.write_text(json.dumps(payload, indent=2) + "\n")
    temporary.replace(output / "results.json")
    fields = (
        "adapter",
        "operation",
        "size_bytes",
        "workers",
        "cache",
        "samples",
        "failed_samples",
        "median_ms",
        "p95_ms",
        "ops_s",
        "http_per_op",
        "logical_mib_s",
    )
    with (output / "summary.csv").open("w", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=fields)
        writer.writeheader()
        writer.writerows(summary)
    lines = [
        "# S3 benchmark",
        "",
        f"Run: `{metadata['run_id']}`",
        f"Status: **{metadata['status']}**; cleanup: **{metadata.get('cleanup', 'pending')}**",
        "",
        "Cold means client metadata cache invalidated before a batch; "
        "server, OS and connection caches are not reset. Warm means an initialized "
        "client with caches retained, not guaranteed cache hits.",
        "",
        "Thread concurrency uses the synchronous API. HTTP counts include retries, "
        "exclude fixture setup and validation. Latencies include node construction. "
        "Throughput for copy/move is logical object size, not network traffic.",
        "",
        "| Client | Operation | Bytes | Workers | Cache | n / failed | Median ms | "
        "p95 ms | Ops/s | HTTP/op |",
        "|---|---|---:|---:|---|---:|---:|---:|---:|---:|",
    ]
    for row in summary:

        def metric(name):
            return f"{row[name]:.3f}" if name in row else "—"

        lines.append(
            f"| {row['adapter']} | {row['operation']} | {row['size_bytes']} | "
            f"{row['workers']} | {row['cache']} | {row['samples']} / "
            f"{row['failed_samples']} | {metric('median_ms')} | {metric('p95_ms')} | "
            f"{metric('ops_s')} | {metric('http_per_op')} |"
        )
    lines += [
        "",
        "Initialization has one observation per client, not a reliable percentile. "
        "Warmup samples are retained in JSON but excluded from this table. "
        "A failed correctness check invalidates the entire sample. "
        "Read results.json for versions, effective settings, per-operation HTTP counts "
        "and individual measurements.",
        "",
    ]
    (output / "report.md").write_text("\n".join(lines))


def run(target, options, legacy=None):
    run_id = str(uuid.uuid4())
    output = options.output / run_id
    fixtures = Fixtures(target, run_id)
    root = Path(__file__).resolve().parents[1]
    packages = {}
    for name in (
        "genro-storage",
        "fsspec",
        "s3fs",
        "boto3",
        "botocore",
        "aiobotocore",
        "smart_open",
        "genro-toolbox",
    ):
        try:
            packages[name] = importlib.metadata.version(name)
        except importlib.metadata.PackageNotFoundError:
            packages[name] = None
    import genro_storage

    metadata = dict(
        run_id=run_id,
        status="running",
        cleanup="pending",
        target=options.target,
        endpoint_host=options.endpoint_host,
        bucket=target.bucket,
        prefix=fixtures.prefix,
        region=target.region,
        python=platform.python_version(),
        platform=platform.platform(),
        versions=packages,
        genro_source=str(Path(genro_storage.__file__).resolve()),
        genro_revision=revision(root),
        genro_source_sha256=source_digest(root, "src/genro_storage/**/*.py"),
        benchmark_source_sha256=source_digest(root, "benchmarks/*.py"),
        genro_source_version=genro_storage.__version__,
        legacy_revision=revision(options.legacy_root) if options.legacy_root else None,
        legacy_service_sha256=source_digest(
            options.legacy_root,
            "projects/gnrcore/packages/sys/resources/services/storage/aws_s3.py",
        )
        if options.legacy_root
        else None,
        parameters=dict(
            sizes=options.sizes,
            list_count=options.list_count,
            repeats=options.repeats,
            warmups=options.warmups,
            workers=options.workers,
            operations=options.operations,
            calls_per_worker=options.calls,
            history=options.history,
            caches=options.caches,
            seed=options.seed,
        ),
        effective_clients={},
    )
    samples, adapters = [], {}
    save_report(output, metadata, samples)
    print(f"Results: {output}", flush=True)
    try:
        fixtures.prepare(options.sizes, options.list_count, options.history)
        metadata["bucket_versioned"] = fixtures.versioned
        for name in options.adapters:
            start = time.perf_counter()
            adapter = build_adapter(name, target, fixtures.prefix, legacy)
            adapters[name] = adapter
            exists = adapter.exists(f"files/{options.sizes[0]}.bin")
            elapsed = time.perf_counter() - start
            samples.append(
                dict(
                    adapter=name,
                    operation="client_start_and_exists",
                    size_bytes=options.sizes[0],
                    workers=1,
                    cache="fresh",
                    warmup=False,
                    elapsed_s=elapsed,
                    latencies_s=[elapsed],
                    requests=adapter.requests.snapshot(),
                    errors=[] if exists else ["AssertionError"],
                    calls=1,
                )
            )
            if hasattr(adapter, "fs"):
                fs = adapter.fs
                metadata["effective_clients"][name] = dict(
                    version_aware=fs.version_aware,
                    block_size=fs.default_block_size,
                    cache_type=fs.default_cache_type,
                    listings_cache=fs.dircache.use_listings_cache,
                )
        jobs = []
        for op in options.operations:
            sizes = (
                options.sizes
                if op in ("read", "write", "copy", "move", "local_path")
                else options.sizes[:1]
            )
            for size in sizes:
                for workers in options.workers:
                    for cache in options.caches:
                        for name in adapters:
                            jobs.append((name, op, size, workers, cache))
        rng = random.Random(options.seed)
        # All clients see the same fixture set. Shuffle order every round to
        # reduce systematic ordering bias. Pools persist outside timed sections.
        with ExitStack() as stack:
            pools = {
                workers: stack.enter_context(ThreadPoolExecutor(max_workers=workers))
                for workers in options.workers
                if workers > 1
            }
            for workers, pool in pools.items():
                barrier = Barrier(workers)
                list(pool.map(lambda _: barrier.wait(timeout=30), range(workers)))
            for round_index in range(-options.warmups, options.repeats):
                rng.shuffle(jobs)
                for name, op, size, workers, cache in jobs:
                    result = trial(
                        adapters[name],
                        fixtures,
                        op,
                        size,
                        workers,
                        workers * options.calls,
                        cache,
                        pools.get(workers),
                        options.list_count,
                    )
                    samples.append(
                        dict(
                            adapter=name,
                            operation=op,
                            size_bytes=size,
                            workers=workers,
                            cache=cache,
                            warmup=round_index < 0,
                            round=round_index,
                            **result,
                        )
                    )
                    if len(samples) % 50 == 0:
                        save_report(output, metadata, samples)
                        print(
                            f"Round {round_index + 1}: {len(samples)} batches recorded", flush=True
                        )
                save_report(output, metadata, samples)
                print(
                    f"Round {round_index + 1}/{options.repeats}: "
                    f"{sum(bool(s['errors']) for s in samples)} failed samples",
                    flush=True,
                )
        metadata["status"] = "failed" if any(s["errors"] for s in samples) else "complete"
    except BaseException as exc:
        metadata["status"] = "failed"
        metadata["error_type"] = type(exc).__name__
        # Preserve a report without potentially credential-bearing exception text.
        raise
    finally:
        try:
            fixtures.cleanup()
            metadata["cleanup"] = "complete"
        except Exception as exc:
            metadata["cleanup"] = "failed:" + type(exc).__name__
            metadata["status"] = "failed"
        for name, adapter in adapters.items():
            try:
                adapter.close()
            except Exception as exc:
                metadata.setdefault("close_errors", {})[name] = type(exc).__name__
        fixtures.client.close()
        save_report(output, metadata, samples)
    return output, metadata["status"] == "complete"
